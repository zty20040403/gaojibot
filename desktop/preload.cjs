'use strict';

const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('gaojiDesktop', Object.freeze({
  info: () => ipcRenderer.invoke('gaoji:info'),
  appUpdateStatus: () => ipcRenderer.invoke('gaoji:app-update-status'),
  checkAppUpdate: () => ipcRenderer.invoke('gaoji:app-update-check'),
  downloadAppUpdate: () => ipcRenderer.invoke('gaoji:app-update-download'),
  installAppUpdate: () => ipcRenderer.invoke('gaoji:app-update-install'),
  onAppUpdateRequested: callback => {
    const listener = () => callback();
    ipcRenderer.on('gaoji:show-app-update', listener);
    return () => ipcRenderer.removeListener('gaoji:show-app-update', listener);
  },
  localInspect: () => ipcRenderer.invoke('gaoji:local-inspect'),
  localStart: options => ipcRenderer.invoke('gaoji:local-start', options),
  localStatus: () => ipcRenderer.invoke('gaoji:local-status'),
  localDocker: action => ipcRenderer.invoke('gaoji:local-docker', action),
  servers: () => ipcRenderer.invoke('gaoji:servers'),
  applicationCatalog: () => ipcRenderer.invoke('gaoji:application-catalog'),
  applications: id => ipcRenderer.invoke('gaoji:applications', id),
  applicationStatus: id => ipcRenderer.invoke('gaoji:application-status', id),
  renameApplication: request => ipcRenderer.invoke('gaoji:application-rename', request),
  removeApplicationDraft: request => ipcRenderer.invoke('gaoji:application-remove-draft', request),
  createApplication: request => ipcRenderer.invoke('gaoji:application-create', request),
  selectWebsite: () => ipcRenderer.invoke('gaoji:website-select'),
  websiteStatus: id => ipcRenderer.invoke('gaoji:website-status', id),
  websiteSubmit: request => ipcRenderer.invoke('gaoji:website-submit', request),
  websiteResume: request => ipcRenderer.invoke('gaoji:website-resume', request),
  websiteBackupExport: request => ipcRenderer.invoke('gaoji:website-backup-export', request),
  websiteBackupImport: request => ipcRenderer.invoke('gaoji:website-backup-import', request),
  openWebsite: id => ipcRenderer.invoke('gaoji:website-open', id),
  exportDiagnostics: report => ipcRenderer.invoke('gaoji:diagnostics-export', report),
  selectKey: () => ipcRenderer.invoke('gaoji:select-key'),
  discover: target => ipcRenderer.invoke('gaoji:discover', target),
  connect: request => ipcRenderer.invoke('gaoji:connect', request),
  inspect: id => ipcRenderer.invoke('gaoji:inspect', id),
  install: request => ipcRenderer.invoke('gaoji:install', request),
  installStatus: id => ipcRenderer.invoke('gaoji:install-status', id),
  updatePlan: id => ipcRenderer.invoke('gaoji:update-plan', id),
  updateStatus: id => ipcRenderer.invoke('gaoji:update-status', id),
  update: request => ipcRenderer.invoke('gaoji:update', request),
  resumeUpdate: request => ipcRenderer.invoke('gaoji:update-resume', request),
  lifecyclePrepare: request => ipcRenderer.invoke('gaoji:lifecycle-prepare', request),
  lifecycleSubmit: request => ipcRenderer.invoke('gaoji:lifecycle-submit', request),
  lifecycleStatus: id => ipcRenderer.invoke('gaoji:lifecycle-status', id),
  selectBackup: () => ipcRenderer.invoke('gaoji:backup-select'),
  exportBackup: request => ipcRenderer.invoke('gaoji:backup-export', request),
  importBackup: request => ipcRenderer.invoke('gaoji:backup-import', request),
  backupTransferStatus: id => ipcRenderer.invoke('gaoji:backup-transfer-status', id),
  cancelBackupTransfer: id => ipcRenderer.invoke('gaoji:backup-transfer-cancel', id),
  instance: request => ipcRenderer.invoke('gaoji:instance', request),
  openConsole: id => ipcRenderer.invoke('gaoji:open-console', id),
  forget: id => ipcRenderer.invoke('gaoji:forget', id),
}));
