'use strict';

const assert = require('node:assert/strict');
const path = require('node:path');

module.exports = async function verifyModels(page, app, directory) {
  await page.setViewportSize({ width: 1280, height: 1000 });
  await page.getByText('04 / 配置模型', { exact: true }).waitFor();
  await page.getByRole('switch', { name: '语义记忆检索', exact: true }).uncheck();
  await page.getByLabel('模型显示名称', { exact: true }).fill('日常聊天');
  assert.equal(await page.getByLabel('默认聊天模型', { exact: true }).inputValue(), 'primary');
  await page.getByRole('button', { name: '删除此模型', exact: true }).isDisabled().then(value => assert.equal(value, true));
  await page.getByRole('button', { name: '添加模型', exact: true }).click();
  const beta = await page.getByLabel('正在编辑的模型', { exact: true }).inputValue();
  assert.notEqual(beta, 'primary');
  assert.equal(await page.getByLabel('默认聊天模型', { exact: true }).inputValue(), 'primary');
  await page.getByLabel('模型显示名称', { exact: true }).fill('写代码');
  await page.getByLabel('模型服务', { exact: true }).selectOption('openai');
  await page.getByLabel('API 地址', { exact: true }).fill('https://code-fixture.invalid/v1');
  await page.getByLabel('模型名称', { exact: true }).fill('code-fixture-model');
  await page.getByLabel(/^API Key/).fill('code-fixture-secret');
  if (await page.locator('.model-catalog details').getAttribute('open') === null) await page.getByText('模型高级设置', { exact: true }).click();
  await page.getByLabel('推理强度', { exact: true }).selectOption('xhigh');
  await page.getByLabel('输入 Token 上限（0 为自动）', { exact: true }).fill('131072');
  await page.getByLabel('输出 Token 上限（0 为默认）', { exact: true }).fill('8192');
  await page.getByLabel('模型支持识图', { exact: true }).check();
  await page.getByLabel('正在编辑的模型', { exact: true }).selectOption('primary');
  assert.equal(await page.getByLabel(/^API Key/).inputValue(), '');
  await page.getByLabel('正在编辑的模型', { exact: true }).selectOption(beta);
  assert.equal(await page.getByLabel(/^API Key/).inputValue(), 'code-fixture-secret');
  assert.equal(await page.getByLabel('推理强度', { exact: true }).inputValue(), 'xhigh');

  await page.getByRole('button', { name: '添加模型', exact: true }).click();
  const gamma = await page.getByLabel('正在编辑的模型', { exact: true }).inputValue();
  await page.getByLabel('模型显示名称', { exact: true }).fill('图片与整理');
  await page.getByLabel('模型服务', { exact: true }).selectOption('qwen');
  await page.getByLabel('API 地址', { exact: true }).fill('http://qwen-fixture.invalid:8000/v1');
  await page.getByLabel('模型名称', { exact: true }).fill('qwen-fixture-model');
  await page.getByLabel('此服务不需要 API Key', { exact: true }).check();
  await page.getByLabel('模型支持识图', { exact: true }).check();
  await page.getByLabel('思考模式', { exact: true }).selectOption('enabled');
  await page.getByRole('switch', { name: '识图与表情库', exact: true }).check();
  await page.getByRole('switch', { name: '聊天章节整理', exact: true }).check();
  await page.getByLabel('识图模型', { exact: true }).selectOption(gamma);
  await page.getByLabel('整理模型', { exact: true }).selectOption(gamma);
  await page.getByRole('switch', { name: '视频深入分析', exact: true }).check();
  await page.getByText('应用时下载', { exact: true }).waitFor();
  await page.getByLabel('转写 CPU 线程', { exact: true }).fill('3');
  await page.getByLabel('关键帧数量', { exact: true }).fill('6');
  await page.getByLabel('单条下载上限（MiB）', { exact: true }).fill('128');
  await page.getByLabel('正在编辑的模型', { exact: true }).selectOption(beta);
  await page.getByLabel('添加备选模型', { exact: true }).selectOption(gamma);
  await page.getByLabel('正在编辑的模型', { exact: true }).selectOption('primary');
  await page.getByLabel('添加备选模型', { exact: true }).selectOption(beta);
  await page.getByLabel('添加备选模型', { exact: true }).selectOption(gamma);
  await page.getByRole('button', { name: '下移备选模型 1', exact: true }).click();
  assert.deepEqual(await page.locator('.fallback-row strong').allTextContents(), ['图片与整理', '写代码']);
  await page.getByLabel('正在编辑的模型', { exact: true }).selectOption(gamma);
  await page.getByLabel('添加备选模型', { exact: true }).locator('option[value="primary"]:disabled').waitFor({ state: 'attached' });
  const revision = await app.evaluate(() => globalThis.setupFixture.status.instance.revision);
  await page.getByRole('button', { name: '保存设置', exact: true }).click();
  await page.getByText(`配置版本 ${revision + 1}`, { exact: false }).waitFor();
  const saved = await app.evaluate(() => globalThis.setupFixture.calls.filter(item => item.action === 'save').at(-1).payload);
  assert.equal(saved.settings.default_model, 'primary');
  assert.equal(saved.settings.vision_model, gamma);
  assert.equal(saved.settings.components.historian.profile, gamma);
  assert.deepEqual(saved.settings.models.find(item => item.id === 'primary').fallbacks, [gamma, beta]);
  assert.deepEqual(saved.model_keys, { [beta]: 'code-fixture-secret', [gamma]: '' });
  assert.equal(saved.settings.models.find(item => item.id === beta).reasoning_effort, 'xhigh');
  assert.equal(saved.settings.models.find(item => item.id === gamma).thinking, 'enabled');
  assert.equal(saved.settings.features.video, true);
  assert.equal(saved.settings.components.video.threads, 3);
  assert.equal(saved.settings.components.video.max_download_mb, 128);
  assert.equal(JSON.stringify(saved.settings).includes('code-fixture-secret'), false);

  await page.getByRole('button', { name: '删除此模型', exact: true }).click();
  await page.getByRole('dialog').waitFor();
  await page.getByRole('button', { name: '取消删除模型', exact: true }).click();
  assert.equal(await page.getByLabel('正在编辑的模型', { exact: true }).locator('option').count(), 3);
  await page.getByRole('button', { name: '删除此模型', exact: true }).click();
  await page.getByRole('button', { name: '确认删除模型', exact: true }).click();
  assert.equal(await page.getByLabel('正在编辑的模型', { exact: true }).locator('option').count(), 2);
  assert.equal(await page.getByLabel('识图模型', { exact: true }).inputValue(), '');
  assert.equal(await page.getByLabel('整理模型', { exact: true }).inputValue(), '');
  await page.getByLabel('识图模型', { exact: true }).selectOption(beta);
  await page.getByRole('button', { name: '保存设置', exact: true }).click();
  await page.getByText(`配置版本 ${revision + 2}`, { exact: false }).waitFor();
  const deleted = await app.evaluate(() => globalThis.setupFixture.calls.filter(item => item.action === 'save').at(-1).payload);
  assert.deepEqual(deleted.model_keys, {});
  assert.equal(deleted.settings.models.some(item => item.id === gamma), false);
  assert.deepEqual(deleted.settings.models.find(item => item.id === beta).fallbacks, []);
  assert.deepEqual(deleted.settings.models.find(item => item.id === 'primary').fallbacks, [beta]);

  await page.getByLabel('正在编辑的模型', { exact: true }).selectOption(beta);
  await page.getByRole('button', { name: '测试连接', exact: true }).click();
  await page.getByText('模型已返回文字，耗时 0.1 秒', { exact: true }).waitFor();
  const probe = await app.evaluate(() => globalThis.setupFixture.calls.filter(item => item.action === 'modelTest').at(-1).payload);
  assert.equal(probe.model.id, beta); assert.equal(probe.key, null); assert.equal(probe.model.reasoning_effort, 'xhigh');
  await page.getByLabel('API 地址', { exact: true }).fill('https://changed-code-fixture.invalid/v1');
  await page.getByLabel('正在编辑的模型', { exact: true }).selectOption('primary');
  const attempts = await app.evaluate(() => globalThis.setupFixture.calls.filter(item => item.action === 'save').length);
  await page.getByRole('button', { name: '保存设置', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: '写代码' }).waitFor();
  assert.equal(await app.evaluate(() => globalThis.setupFixture.calls.filter(item => item.action === 'save').length), attempts);
  await page.getByLabel('正在编辑的模型', { exact: true }).selectOption(beta);
  assert.equal(await page.getByLabel(/^API Key/).inputValue(), '');
  await page.getByLabel(/^API Key/).fill('new-code-fixture-secret');
  await page.getByLabel('推理强度', { exact: true }).focus();
  await page.evaluate(() => { window.effortSelect = document.activeElement; });
  await page.waitForTimeout(4500);
  assert.equal(await page.evaluate(() => window.effortSelect === document.activeElement && window.effortSelect.isConnected), true);
  assert.equal(await page.getByLabel(/^API Key/).inputValue(), 'new-code-fixture-secret');

  await app.evaluate(() => { const current = globalThis.setupFixture.status.instance; current.revision++; current.settings.name = '其他管理员的新名称'; });
  await page.getByRole('button', { name: '保存设置', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: '配置已被更改' }).waitFor();
  await page.getByRole('button', { name: '重新载入服务器配置', exact: true }).click();
  await page.getByRole('dialog').waitFor();
  await page.getByRole('button', { name: '保留当前编辑', exact: true }).click();
  assert.equal(await page.getByLabel(/^API Key/).inputValue(), 'new-code-fixture-secret');
  await page.getByRole('button', { name: '重新载入服务器配置', exact: true }).click();
  await page.getByRole('button', { name: '丢弃并重新载入', exact: true }).click();
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  assert.equal(await page.getByLabel('机器人名称', { exact: true }).inputValue(), '其他管理员的新名称');
  assert.equal(await page.getByLabel(/^API Key/).inputValue(), '');
  assert.equal(await page.getByLabel('API 地址', { exact: true }).inputValue(), 'https://code-fixture.invalid/v1');
  await page.locator('.model-catalog').screenshot({ path: path.join(directory, 'models-desktop.png') });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.locator('.catalog-picker').screenshot({ path: path.join(directory, 'models-picker-mobile.png') });
  await page.locator('.model-catalog details').screenshot({ path: path.join(directory, 'models-options-mobile.png') });
  await app.evaluate(() => { const model = globalThis.setupFixture.status.video_model; model.state = 'installed'; model.downloaded_bytes = model.total_bytes; });
  await page.getByText('模型已下载', { exact: true }).waitFor({ timeout: 12000 });
  assert.equal(await page.getByLabel('关键帧数量', { exact: true }).inputValue(), '6');
  await page.locator('.component-options').filter({ has: page.getByRole('heading', { name: '视频分析', exact: true }) }).screenshot({ path: path.join(directory, 'component-video-mobile.png') });
  await app.evaluate(() => { globalThis.setupFixture.delayNextModelTest = true; });
  await page.getByRole('button', { name: '测试连接', exact: true }).click();
  await page.locator('.setup-busy').waitFor();
  await app.evaluate(() => {
    const fixture = globalThis.setupFixture;
    fixture.status.instance.revision++;
    fixture.status.instance.settings.name = '恢复后的机器人';
    fixture.status.operation = { id: 'restore-model-fixture', kind: 'restore', status: 'completed', stage: 'restored', message: '恢复已核对' };
  });
  await page.getByLabel('机器人名称', { exact: true }).evaluate(async element => {
    const deadline = Date.now() + 10000;
    while (element.value !== '恢复后的机器人' && Date.now() < deadline) await new Promise(resolve => setTimeout(resolve, 50));
    if (element.value !== '恢复后的机器人') throw new Error('Restored configuration did not load');
  });
  await app.evaluate(() => { globalThis.setupFixture.finishModelTest(); });
  await page.locator('.setup-busy').waitFor({ state: 'hidden' });
  assert.equal(await page.getByText('模型已返回文字，耗时 0.1 秒', { exact: true }).count(), 0);
  console.log('Model UI passed: independent draft keys, default/vision/Historian roles, ordered fallbacks, cycle prevention, deletion, version-conflict reload, stale probe suppression.');
};
